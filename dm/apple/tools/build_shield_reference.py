#!/usr/bin/env python3
"""Compile the reviewed, asset-free handbook. Requires only checked-in JSON."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    rows = json.loads((ROOT / 'shield_guide_reference.json').read_text())
    keys = set()
    for row in rows:
        assert set(row) == {'key', 'category', 'title', 'body', 'citation'}, row
        assert all(isinstance(v, str) and v.strip() for v in row.values()), row
        assert row['key'] not in keys, row['key']
        assert not any(token in row['body'] for token in ('<img', '![](', 'data-bbox', 'control:')), row
        keys.add(row['key'])
    # Escape JSON once for JSON and again for a C string. Separate literals keep
    # source lines short without splitting escapes or UTF-8 characters.
    payload = json.dumps(rows, ensure_ascii=False, separators=(',', ':'))
    lines = ['// Generated by tools/build_shield_reference.py; edit the reviewed JSON.',
             'static const char shieldReferenceJSON[] =']
    for offset in range(0, len(payload), 1000):
        lines.append(json.dumps(payload[offset:offset + 1000], ensure_ascii=False))
    return '\n'.join(lines) + ';\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'shield_guide_reference.inc'
    expected = build()
    if args.check:
        if not path.exists() or path.read_text() != expected:
            raise SystemExit('Stale Shield handbook; run dm/apple/tools/build_shield_reference.py')
        print('PASS: compiled Shield handbook matches reviewed JSON')
    else:
        path.write_text(expected)
